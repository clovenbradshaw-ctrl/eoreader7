// eval/capacity-map/summarize.mjs — turns the drivers' JSON into the tables of
// results/RESULTS.md, so no number in THE-CAPACITY-MAP.md section 7 is typed by hand.
// Usage: node summarize.mjs   (reads results/*.json, writes results/RESULTS.md)
import fs from "node:fs";

const dir = new URL("./results/", import.meta.url);
const read = (name) => JSON.parse(fs.readFileSync(new URL(name, dir), "utf8"));
const exists = (name) => fs.existsSync(new URL(name, dir));
const f = (x, d = 3) => (Number.isFinite(x) ? x.toFixed(d) : "n/a");
const out = [];
const p = (s = "") => out.push(s);

p("# Capacity map — results (generated by summarize.mjs; do not edit by hand)");
p();

// ── F3 ──
const f3 = read("f3-layering.json");
p("## F3 — is the strict order a fact about how the system is built?");
p();
p(`Population: **${f3.population.total}** modules (arithmetic ${f3.population.byClass.arithmetic}, geometric ${f3.population.byClass.geometric}, transcendental ${f3.population.byClass.transcendental}). `
  + `Listed, not dropped: ${f3.listed.ambiguous.length} ambiguous basenames, ${f3.listed.unresolved.length} CAPACITIES entries whose module is not under native/ (they live in the-fold), ${f3.listed.conflicts.length} class conflicts, ${f3.listed.multiDomain.length} multi-domain and ${f3.listed.multiGrain.length} multi-grain modules.`);
p();
p("| axis | modules | edges among them | cross edges | upward | null mean | null 5th pct | p_low | verdict |");
p("|---|---|---|---|---|---|---|---|---|");
for (const a of [f3.class, f3.grain]) p(`| ${a.field === "klass" ? "class" : "grain"} | ${a.modules} | ${a.edgesAmong} | ${a.crossEdges} | ${a.upward} | ${f(a.nullMean, 2)} | ${a.null5th} | ${f(a.pLow)} | **${a.verdict}** |`);
p();
p("Upward edges — class:");
for (const e of f3.class.upwardEdges) p(`- ${e}`);
p();
p("Upward edges — grain:");
for (const e of f3.grain.upwardEdges) p(`- ${e}`);
if (exists("f3-layering.run1-full-path-lookup.json")) {
  const r1 = read("f3-layering.run1-full-path-lookup.json");
  p();
  p(`Run 1 (kept): the driver looked up each CAPACITIES entry by its full \`module\` string instead of by basename as the document declares; ${r1.population.total} modules, class ${r1.class.crossEdges} cross / ${r1.class.upward} upward (${r1.class.verdict}), grain ${r1.grain.crossEdges} cross / ${r1.grain.upward} upward (${r1.grain.verdict}). The lookup was corrected to the declared rule and the run repeated; both are reported.`);
}
p();

// ── F4 ──
p("## F4 — does direction need standing?");
p();
if (exists("f4-power.json")) {
  const w = read("f4-power.json");
  p(`Harness power check (${w.syntheses} syntheses; planted pair: B follows A at lag 1 with probability 0.5 over a 0.05 base): planted pair agreement **${f(w.planted.real, 3)}** vs order-destroyed **${f(w.planted.shuf, 3)}** (z ${f(w.planted.z, 1)}); independent pairs **${f(w.independent.real, 3)}** vs **${f(w.independent.shuf, 3)}** (z ${f(w.independent.z, 2)}). ${w.pass ? "PASSED." : "FAILED."}`);
  p();
}
const mats = [["Dracula", "f4-dracula.json"], ["Pride and Prejudice", "f4-pride.json"], ["Frankenstein", "f4-frankenstein.json"], ["Shakespeare plays (38, pooled)", "f4-plays.json"]].filter(([, n]) => exists(n));
const primaryKey = (r) => Object.keys(r.variants).find((k) => k.startsWith("primary"));
p("### Primary setting");
p();
p("| material | pairs | S n | A_S | E_S | p(E_S) | N n | A_N | E_N | p(E_N) | Δ | p(Δ) | strata used | decision |");
p("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|");
for (const [name, file] of mats) {
  const r = read(file);
  const v = r.variants[primaryKey(r)];
  p(`| ${name} | ${v.pairs} | ${v.S.n} | ${f(v.S.A_real)} | ${f(v.S.E)} | ${f(v.S.p_E)} | ${v.N.n} | ${f(v.N.A_real)} | ${f(v.N.E)} | ${f(v.N.p_E)} | ${f(v.contrast.delta)} | ${f(v.contrast.pGreater)} | ${v.contrast.strataUsed} | **${v.decision.label}** |`);
}
p();
p("### Robustness (read for sign and size, never for the decision)");
p();
p("| material | variant | S n | E_S | N n | E_N | Δ | p(Δ) | label |");
p("|---|---|---|---|---|---|---|---|---|");
for (const [name, file] of mats) {
  const r = read(file);
  for (const [k, v] of Object.entries(r.variants)) p(`| ${name} | ${k} | ${v.S.n} | ${f(v.S.E)} | ${v.N.n} | ${f(v.N.E)} | ${f(v.contrast.delta)} | ${f(v.contrast.pGreater)} | ${v.decision.label} |`);
}
p();
const diag = ["dracula", "pride", "frankenstein"].filter((l) => exists(`f4-diagnose-${l}.json`));
if (diag.length) {
  p("### Exploratory diagnosis (post-hoc; changes no verdict above)");
  p();
  p("| book | analysis | S n | E_S | N n | E_N | Δ | p(Δ>0) | p(Δ<0) | strata |");
  p("|---|---|---|---|---|---|---|---|---|---|");
  for (const l of diag) {
    const d = read(`f4-diagnose-${l}.json`);
    for (const row of d.rows) p(`| ${l} | ${row.tag} | ${row.S.n} | ${f(row.S.E)} | ${row.N.n} | ${f(row.N.E)} | ${f(row.c.delta)} | ${f(row.c.pGreater)} | ${f(row.c.pLess)} | ${row.c.strataUsed} |`);
  }
  p();
}

// ── F5 ──
if (exists("f5-units.json")) {
  const r5 = read("f5-units.json");
  p("## F5 — does standing need identity?");
  p();
  p("| book | surface arm: standing / not | referent arm: standing / not | self-edges in top 20 | same-cluster pairs (standing / not) | different-cluster pairs (standing / not) | Fisher p | permuted-label share, 95th pct | consequential |");
  p("|---|---|---|---|---|---|---|---|---|");
  for (const b of r5.books) {
    const t = b.enrichment.table;
    p(`| ${b.path.split("/").pop().replace(/^pg\d+_/, "").replace(".txt", "")} | ${b.surfaceArm.standing} / ${b.surfaceArm.notStanding} | ${b.referentArm.standing} / ${b.referentArm.notStanding} | ${b.selfInTop}/${b.topN} = ${f(b.share_self, 2)} | ${t.a} / ${t.b} | ${t.c} / ${t.d} | ${f(b.enrichment.fisherP, 4)} | ${f(b.permutedLabels.p95share, 2)} | ${b.consequential} |`);
  }
  p();
  p(`Overall (declared rule): **${r5.overall}**.`);
  p();
}
fs.writeFileSync(new URL("RESULTS.md", dir), out.join("\n") + "\n");
console.log(`wrote results/RESULTS.md (${out.length} lines)`);
